it("writes correct reverse edges idempotently and refuses outside-tasks dirty data", () => {
  const f = repository();
  try {
    const second = fixture
      .replaceAll("OVE_FIX001", "OVE_FIX002")
      .replace("depends_on: []", "depends_on: [OVE_FIX001]");
    mkdirSync(join(f.root, "tasks/OVE_FIX002"));
    writeFileSync(join(f.root, "tasks/OVE_FIX002/TASK.md"), second);
    f.git("init", "--initial-branch=DEVELOP");
    f.run("--write-blocks");
    const after = readFileSync(join(f.root, "tasks/OVE_FIX001/TASK.md"), "utf8");
    expect(after).toBe(fixture.replace("adr_refs: []\n", "adr_refs: []\nblocks: [OVE_FIX002]\n"));
    expect(readFileSync(join(f.root, "tasks/OVE_FIX002/TASK.md"), "utf8")).toBe(
      second.replace("adr_refs: []\n", "adr_refs: []\nblocks: []\n"),
    );
    f.run("--write-blocks");
    expect(readFileSync(join(f.root, "tasks/OVE_FIX001/TASK.md"), "utf8")).toBe(after);
    writeFileSync(join(f.root, "outside.txt"), "private fixture data");
    expect(f.result("--write-blocks").status).toBe(1);
    expect(readFileSync(join(f.root, "tasks/OVE_FIX001/TASK.md"), "utf8")).toBe(after);
  } finally {
    rmSync(f.root, { recursive: true, force: true });
  }
});

