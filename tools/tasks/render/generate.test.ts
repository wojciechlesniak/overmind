it("preserves newer task bytes when a real Git observer changes input after loading", () => {
  const f = repository();
  try {
    f.run();
    const overview = readFileSync(join(f.root, "tasks/INDEX.md"));
    f.git("init", "--initial-branch=DEVELOP");
    const realGit = realpathSync("/usr/bin/git");
    expect(execFileSync(realGit, ["--version"], { env: f.env, encoding: "utf8" })).toMatch(
      /^git version /u,
    );
    const bin = join(f.root, ".git/observer-bin");
    const marker = join(f.root, ".git/observer-ran");
    const taskPath = join(f.root, "tasks/OVE_FIX001/TASK.md");
    const newer = fixture + "\nConcurrent harmless fixture line.\n";
    mkdirSync(bin);
    const observer = join(bin, "git");
    writeFileSync(
      observer,
      `#!${process.execPath}\nconst fs = require('node:fs');\nif (!fs.existsSync(${JSON.stringify(marker)})) { fs.writeFileSync(${JSON.stringify(marker)}, 'observed'); fs.writeFileSync(${JSON.stringify(taskPath)}, ${JSON.stringify(newer)}); }\nconst result = require('node:child_process').spawnSync(${JSON.stringify(realGit)}, process.argv.slice(2), { stdio: 'inherit' });\nif (result.error) throw result.error; if (result.signal) process.kill(process.pid, result.signal); else process.exitCode = result.status;\n`,
    );
    chmodSync(observer, 0o700);
    Object.assign(f.env, { PATH: bin + ":" + (process.env["PATH"] ?? "") });
    const result = f.result("--write-blocks");
    expect(existsSync(marker)).toBe(true);
    expect(readFileSync(taskPath).equals(Buffer.from(newer))).toBe(true);
    expect(result.status).toBe(1);
    expect(result.stderr).toBe("Task index generation failed\n");
    expect(readFileSync(join(f.root, "tasks/INDEX.md"))).toEqual(overview);
    expect(
      readdirSync(join(f.root, "tasks")).filter((name) => name.startsWith(".task-index-")),
    ).toEqual([]);
  } finally {
    rmSync(f.root, { recursive: true, force: true });
  }
});

it("binds maintainer dirty checks to the actual canonical task worktree", () => {
  const f = repository();
  const redirected = realpathSync(mkdtempSync(join(tmpdir(), "ove-index-other-")));
  try {
    f.run();
    const paths = ["tasks/OVE_FIX001/TASK.md", "tasks/INDEX.md", "tasks/DEPENDENCIES.md"];
    const original = paths.map((path) => readFileSync(join(f.root, path)));
    f.git("init", "--initial-branch=DEVELOP");
    f.git("config", "core.worktree", redirected);
    writeFileSync(join(f.root, "outside.txt"), "harmless fixture change");
    expect(f.git("rev-parse", "--show-toplevel").trim()).toBe(redirected);
    expect(f.git("status", "--porcelain=v1", "--untracked-files=all")).toBe("");
    const denied = f.result("--write-blocks");
    expect(denied.status).toBe(1);
    expect(paths.map((path) => readFileSync(join(f.root, path)))).toEqual(original);
    expect(readFileSync(join(f.root, "outside.txt"), "utf8")).toBe("harmless fixture change");
    f.git("config", "core.worktree", f.root);
    unlinkSync(join(f.root, "outside.txt"));
    expect(f.result("--write-blocks").status).toBe(0);
  } finally {
    rmSync(f.root, { recursive: true, force: true });
    rmSync(redirected, { recursive: true, force: true });
  }
});

it.each([
  ["insertion", "@@ -0,0 +1,1 @@"],
  ["deletion", "@@ -1,1 +0,0 @@"],
])("prints an applicable %s-only diff with correct zero-length ranges", (kind, expectedRange) => {
  const f = repository();
  try {
    f.run();
    f.git("init", "--initial-branch=DEVELOP");
    const path = join(f.root, "tasks/INDEX.md");
    const canonical = readFileSync(path, "utf8");
    const changed =
      kind === "insertion"
        ? canonical.slice("# Task index\n".length)
        : "Unexpected fixture line\n" + canonical;
    writeFileSync(path, changed);
    const result = f.result("--check");
    expect(result.status).toBe(1);
    expect(result.stdout).toContain(expectedRange);
    expect(readFileSync(path, "utf8")).toBe(changed);
    execFileSync("git", ["apply", "--unidiff-zero", "-p0"], {
      cwd: f.root,
      env: f.env,
      input: result.stdout,
    });
    expect(readFileSync(path, "utf8")).toBe(canonical);
  } finally {
    rmSync(f.root, { recursive: true, force: true });
  }
});

