it.each(["symlink", "hardlink"])("refuses an output %s before changing any destination", (kind) => {
  const f = repository();
  try {
    f.run();
    const index = join(f.root, "tasks/INDEX.md");
    const original = readFileSync(join(f.root, "tasks/DEPENDENCIES.md"));
    const outside = join(f.root, "outside.md");
    writeFileSync(outside, "private fixture bytes");
    unlinkSync(index);
    if (kind === "symlink") {
      symlinkSync(outside, index);
    } else {
      linkSync(outside, index);
    }
    expect(f.result().status).toBe(1);
    expect(readFileSync(outside, "utf8")).toBe("private fixture bytes");
    expect(readFileSync(join(f.root, "tasks/DEPENDENCIES.md"))).toEqual(original);
    expect(
      readdirSync(join(f.root, "tasks")).filter((name) => name.startsWith(".task-index-")),
    ).toEqual([]);
  } finally {
    rmSync(f.root, { recursive: true, force: true });
  }
});

