const cli = fileURLToPath(new URL("../gen-index.ts", import.meta.url));
const fixture = readFileSync(
  new URL("../fixtures/tasks/OVE_FIX001/TASK.md", import.meta.url),
  "utf8",
);
function repository() {
  const root = realpathSync(mkdtempSync(join(tmpdir(), "ove-index-")));
  const home = join(root, "home");
  mkdirSync(home);
  mkdirSync(join(root, "tasks/OVE_FIX001"), { recursive: true });
  writeFileSync(join(root, "tasks/PLAN.md"), "## 2. Area codes\n\n| FIX | Fixture | 1 |\n");
  writeFileSync(join(root, "tasks/OVE_FIX001/TASK.md"), fixture);
  const env = { ...isolatedGitEnvironment(), HOME: home, XDG_CONFIG_HOME: home };
  return {
    root,
    env,
    git: (...args: string[]) => execFileSync("git", args, { cwd: root, env, encoding: "utf8" }),
    result: (...args: string[]) =>
      spawnSync(process.execPath, ["--import", import.meta.resolve("tsx"), cli, ...args], {
        cwd: root,
        env,
        encoding: "utf8",
      }),
    run: (...args: string[]) =>
      execFileSync(process.execPath, ["--import", import.meta.resolve("tsx"), cli, ...args], {
        cwd: root,
        env,
        encoding: "utf8",
      }),
  };
}

it("writes a static index through the real CLI and produces identical bytes twice", () => {
  const f = repository();
  try {
    f.run();
    const first = readFileSync(join(f.root, "tasks/INDEX.md"), "utf8");
    expect(first).toContain("Generated by `pnpm gen:task-index`. Do not edit.");
    expect(first).toContain(
      "| [OVE_FIX001](OVE_FIX001/TASK.md) | Verify task tooling against a temporary repository | test | S | P0 | yes | - | lib:fixture |",
    );
    expect(first).not.toMatch(/status|todo|in_progress|done|20\d\d-\d\d-\d\d/iu);
    f.run();
    expect(readFileSync(join(f.root, "tasks/INDEX.md"), "utf8")).toBe(first);
    expect(readFileSync(join(f.root, "tasks/DEPENDENCIES.md"), "utf8")).toContain("Critical path");
  } finally {
    rmSync(f.root, { recursive: true, force: true });
  }
});

it("checks bytes without writing and prints a unified diff for a changed title", () => {
  const f = repository();
  try {
    f.run();
    expect(f.result("--check").status).toBe(0);
    const original = readFileSync(join(f.root, "tasks/INDEX.md"), "utf8");
    writeFileSync(
      join(f.root, "tasks/OVE_FIX001/TASK.md"),
      fixture.replace(
        "title: Verify task tooling against a temporary repository",
        "title: Changed title",
      ),
    );
    const result = f.result("--check");
    expect(result.status).toBe(1);
    expect(result.stdout).toContain("--- tasks/INDEX.md\n+++ tasks/INDEX.md\n@@");
    expect(result.stdout).toContain("+| [OVE_FIX001](OVE_FIX001/TASK.md) | Changed title |");
    expect(readFileSync(join(f.root, "tasks/INDEX.md"), "utf8")).toBe(original);
    expect(result.stdout).not.toContain(f.root);
  } finally {
    rmSync(f.root, { recursive: true, force: true });
  }
});

