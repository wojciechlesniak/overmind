import type { Task } from "../lib/index.ts";

export function escapeCell(text: string): string {
  return text
    .replace(/[\\[\]!*~]/gu, "\\$&")
    .replaceAll("&", "&amp;")
    .replaceAll("|", "\\|")
    .replaceAll("`", "&#96;")
    .replaceAll("<", "&lt;")
    .replaceAll(">", "&gt;")
    .replace(/[\r\n]/gu, " ");
}
export function sorted(tasks: ReadonlyMap<string, Task>): Task[] {
  return [...tasks.values()].sort((a, b) => a.id.localeCompare(b.id, "en"));
}
export function taskList(ids: readonly string[]): string {
  return [...new Set(ids)].sort().map(escapeCell).join(", ") || "-";
}
export const generated = "Generated by `pnpm gen:task-index`. Do not edit.";
export function renderIndex(
  tasks: ReadonlyMap<string, Task>,
  areas = [...new Set(sorted(tasks).map((task) => task.area))],
): string {
  const active = sorted(tasks).filter((task) => task.status !== "cancelled");
  const lines = [
    "# Task index",
    "",
    generated,
    "",
    "## Summary",
    "",
    "| Area | Tasks | P0 | P1 | P2 | XS | S | M |",
    "| --- | --- | --- | --- | --- | --- | --- | --- |",
  ];
  for (const area of areas) {
    const group = active.filter((task) => task.area === area);
    lines.push(
      `| ${area} | ${String(group.length)} | ${["P0", "P1", "P2"].map((priority) => group.filter((task) => task.priority === priority).length).join(" | ")} | ${["XS", "S", "M"].map((size) => group.filter((task) => task.size === size).length).join(" | ")} |`,
    );
  }
  const table = (heading: string, group: Task[]) => {
    lines.push(
      "",
      `## ${heading}`,
      "",
      "| ID | Title | Kind | Size | Priority | MVP | Depends on | Provides |",
      "| --- | --- | --- | --- | --- | --- | --- | --- |",
    );
    for (const task of group) {
      lines.push(
        `| [${task.id}](${task.id}/TASK.md) | ${escapeCell(task.title)} | ${task.kind} | ${task.size} | ${task.priority} | ${task.mvp ? "yes" : "no"} | ${taskList(task.depends_on)} | ${taskList(task.provides)} |`,
      );
    }
  };
  for (const area of areas) {
    table(
      area,
      active.filter((task) => task.area === area),
    );
  }
  table(
    "Cancelled",
    sorted(tasks).filter((task) => task.status === "cancelled"),
  );
  return lines.join("\n") + "\n";
}
