import { execFileSync, spawnSync } from "node:child_process";
import { existsSync, mkdirSync, mkdtempSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { resolve } from "node:path";
import { expect, it } from "vitest";
import { isolatedGitEnvironment } from "../hooks/git-test-environment.ts";

const repository = resolve(import.meta.dirname, "../..");
const probe = `
import { createRequire } from "node:module";
import { discoverPluginPaths, renderPluginRegistry } from "./tools/docs-check/plugin-registry.ts";
const require = createRequire(import.meta.url);
const compilerLoaded = () => Object.keys(require.cache).some(path => path.endsWith("/typescript/lib/typescript.js"));
const before = compilerLoaded();
const rendered = renderPluginRegistry([]);
try {
  const paths = await discoverPluginPaths(process.env.DOCS_FIXTURE);
  console.log(JSON.stringify({ before, rendered, paths, compilerLoaded: compilerLoaded() }));
} catch (error) {
  console.log(JSON.stringify({ before, rendered, failure: error.message, compilerLoaded: compilerLoaded() }));
}
`;

it.each(["empty", "valid", "malformed"])(
  "fresh registry process loads the compiler only for a %s inventory that needs admission",
  (kind) => {
    const root = mkdtempSync(resolve(tmpdir(), "ove-doc-compiler-startup-"));
    try {
      const env = isolatedGitEnvironment();
      execFileSync("git", ["init", "--quiet", root], { env });
      if (kind !== "empty") {
        mkdirSync(resolve(root, "tools/docs-probe"), { recursive: true });
        writeFileSync(
          resolve(root, "tools/docs-probe/check.ts"),
          `import { writeFileSync } from "node:fs"; writeFileSync(${JSON.stringify(resolve(root, "executed.marker"))}, "executed"); export default { name: "probe", run() { return []; } };` +
            (kind === "malformed" ? " export const = ;" : ""),
        );
        execFileSync("git", ["-C", root, "add", "."], { env });
      }
      const checked = spawnSync(
        process.execPath,
        ["--import", import.meta.resolve("tsx"), "--input-type=module", "-e", probe],
        { cwd: repository, env: { ...env, DOCS_FIXTURE: root }, encoding: "utf8", timeout: 3000 },
      );
      expect(checked.error).toBeUndefined();
      expect(checked.status, checked.stderr).toBe(0);
      expect(checked.stdout).toBe(
        JSON.stringify({
          before: false,
          rendered:
            "// SPDX-License-Identifier: Apache-2.0\n" +
            "// Generated by the documentation plugin registry generator. Do not edit.\n\n" +
            "export const pluginRegistry: Readonly<Record<string, unknown>> = Object.freeze({});\n",
          ...(kind === "malformed"
            ? { failure: "Documentation plugin inventory could not be admitted." }
            : { paths: kind === "empty" ? [] : ["tools/docs-probe/check.ts"] }),
          compilerLoaded: kind !== "empty",
        }) + "\n",
      );
      expect(existsSync(resolve(root, "executed.marker"))).toBe(false);
    } finally {
      rmSync(root, { recursive: true, force: true });
    }
  },
);
