it.each(["bom", "symlink", "hardlink", "untracked"])(
  "denies a %s output without changing existing bytes or creating temporary files",
  async (kind) => {
    const fixture = registryFixture();
    try {
      if (kind === "bom") {
        writeFileSync(fixture.output, `\uFEFF${renderPluginRegistry([])}`);
      } else if (kind === "symlink") {
        const target = resolve(fixture.root, "retained-registry.ts");
        writeFileSync(target, renderPluginRegistry([]));
        unlinkSync(fixture.output);
        symlinkSync(target, fixture.output);
      } else if (kind === "hardlink") {
        linkSync(fixture.output, resolve(fixture.root, "retained-registry.ts"));
      } else {
        git(fixture.root, "rm", "--cached", "--", "tools/docs-check/plugin-registry.generated.ts");
      }
      const before = readFileSync(fixture.output);
      const original = lstatSync(fixture.output);
      await expect(generatePluginRegistry(fixture.root, "write")).rejects.toThrow(
        "Documentation plugin registry output is unavailable.",
      );
      expect(readFileSync(fixture.output)).toEqual(before);
      expect(lstatSync(fixture.output).ino).toBe(original.ino);
      expect(readdirSync(resolve(fixture.root, "tools/docs-check"))).toEqual([
        "plugin-registry.generated.ts",
      ]);
      expect(existsSync(fixture.marker)).toBe(false);
    } finally {
      rmSync(fixture.root, { recursive: true, force: true });
    }
  },
);

function expectIndependentInventory(root: string, output: string): void {
  const tracked = execFileSync(
    "git",
    ["--no-optional-locks", "-c", "core.fsmonitor=false", "ls-files", "-z", "--cached"],
    {
      cwd: root,
      env: isolatedGitEnvironment(),
      encoding: "utf8",
      timeout: 3000,
    },
  ).split("\0");
  const expected = tracked
    .filter((path) => /^tools\/docs-[a-z0-9-]+\/check\.ts$/u.test(path))
    .sort();
  const parsed = ts.createSourceFile(
    "plugin-registry.generated.ts",
    readFileSync(output, "utf8"),
    ts.ScriptTarget.Latest,
    true,
    ts.ScriptKind.TS,
  );
  const imports = parsed.statements
    .filter(ts.isImportDeclaration)
    .map((node) =>
      ts.isStringLiteral(node.moduleSpecifier) ? node.moduleSpecifier.text : undefined,
    );
  const keys: string[] = [];
  for (const statement of parsed.statements) {
    if (!ts.isVariableStatement(statement)) {
      continue;
    }
    for (const declaration of statement.declarationList.declarations) {
      if (
        !ts.isIdentifier(declaration.name) ||
        declaration.name.text !== "pluginRegistry" ||
        !declaration.initializer ||
        !ts.isCallExpression(declaration.initializer)
      ) {
        continue;
      }
      const record = declaration.initializer.arguments[0];
      if (!record || !ts.isObjectLiteralExpression(record)) {
        continue;
      }
      for (const property of record.properties) {
        if (ts.isPropertyAssignment(property) && ts.isStringLiteral(property.name)) {
          keys.push(property.name.text);
        }
      }
    }
  }
  expect(imports).toEqual(expected.map((path) => `../${path.slice("tools/".length)}`));
  expect(keys).toEqual(expected);
  expect(new Set(imports).size).toBe(imports.length);
  expect(new Set(keys).size).toBe(keys.length);
}

it("regenerates all literal imports and keys after real tracked additions and removals", async () => {
  const fixture = registryFixture();
  try {
    await generatePluginRegistry(fixture.root, "write");
    expectIndependentInventory(fixture.root, fixture.output);
    mkdirSync(resolve(fixture.root, "tools/docs-zeta"));
    writeFileSync(resolve(fixture.root, "tools/docs-zeta/check.ts"), fixture.source);
    git(fixture.root, "add", "--", "tools/docs-zeta/check.ts");
    await generatePluginRegistry(fixture.root, "write");
    expectIndependentInventory(fixture.root, fixture.output);
    git(fixture.root, "rm", "--cached", "--", fixture.file);
    await generatePluginRegistry(fixture.root, "write");
    expectIndependentInventory(fixture.root, fixture.output);
    expect(existsSync(fixture.marker)).toBe(false);
  } finally {
    rmSync(fixture.root, { recursive: true, force: true });
  }
});
