import { execFileSync } from "node:child_process";
import { realpath } from "node:fs/promises";
import * as ts from "typescript";
import { Files } from "../adr/files.ts";
import { isolatedGitEnvironment } from "../hooks/git-test-environment.ts";
import { MAX_DOCUMENT_BYTES, readRepositoryFile } from "./files.ts";
import { documentationPluginPaths } from "./input.parse-boundary.ts";

const registryPath = "tools/docs-check/plugin-registry.generated.ts";
const inventoryFailure = "Documentation plugin inventory could not be admitted.";
const outputFailure = "Documentation plugin registry output is unavailable.";

export function renderPluginRegistry(paths: readonly string[]): string {
  const ordered = documentationPluginPaths(paths);
  if (ordered.length !== paths.length) {
    throw new Error("Invalid documentation plugin inventory.");
  }
  const imports = ordered.map(
    (path, index) =>
      `import * as plugin${String(index)} from ${JSON.stringify(`../${path.slice("tools/".length)}`)};`,
  );
  const entries = ordered.map(
    (path, index) => `  ${JSON.stringify(path)}: plugin${String(index)},`,
  );
  const header =
    "// SPDX-License-Identifier: Apache-2.0\n" +
    "// Generated by the documentation plugin registry generator. Do not edit.\n\n";
  const prelude = imports.length ? `${imports.join("\n")}\n\n` : "";
  const record = entries.length ? `{\n${entries.join("\n")}\n}` : "{}";
  const source =
    header +
    prelude +
    `export const pluginRegistry: Readonly<Record<string, unknown>> = Object.freeze(${record});\n`;
  if (Buffer.byteLength(source) > MAX_DOCUMENT_BYTES) {
    throw new Error("Documentation plugin registry exceeds the byte limit.");
  }
  return source;
}

async function trackedInventory(root: string): Promise<{ root: string; paths: readonly string[] }> {
  try {
    const base = await realpath(root);
    const git = (...args: string[]) => {
      const bytes = execFileSync(
        "git",
        [
          "--no-optional-locks",
          "-c",
          "core.fsmonitor=false",
          "-c",
          "core.untrackedCache=false",
          ...args,
        ],
        {
          cwd: base,
          env: isolatedGitEnvironment(),
          maxBuffer: 8_388_608,
          timeout: 3000,
          stdio: ["ignore", "pipe", "pipe"],
        },
      );
      return new TextDecoder("utf-8", { fatal: true, ignoreBOM: true }).decode(bytes);
    };
    if (git("rev-parse", "--path-format=absolute", "--show-toplevel") !== `${base}\n`) {
      throw new Error("Repository selection mismatch.");
    }
    const raw = git("ls-files", "-z", "--cached");
    if (raw && !raw.endsWith("\0")) {
      throw new Error("Malformed Git inventory.");
    }
    const paths = raw ? raw.slice(0, -1).split("\0") : [];
    documentationPluginPaths(paths);
    return { root: base, paths: Object.freeze(paths) };
  } catch {
    throw new Error(inventoryFailure);
  }
}

async function admitPluginPaths(
  root: string,
  inventory: readonly string[],
): Promise<readonly string[]> {
  try {
    const paths = documentationPluginPaths(inventory);
    for (const path of paths) {
      const source = await readRepositoryFile(root, path, true);
      const parsed = ts.transpileModule(source, {
        fileName: path,
        reportDiagnostics: true,
        compilerOptions: { target: ts.ScriptTarget.ESNext, module: ts.ModuleKind.ESNext },
      });
      if (
        parsed.diagnostics?.some(
          (diagnostic) => diagnostic.category === ts.DiagnosticCategory.Error,
        )
      ) {
        throw new Error("Invalid plugin syntax.");
      }
    }
    return paths;
  } catch {
    throw new Error(inventoryFailure);
  }
}

export async function discoverPluginPaths(root: string): Promise<readonly string[]> {
  const inventory = await trackedInventory(root);
  return admitPluginPaths(inventory.root, inventory.paths);
}

function validateRegistryMode(mode: unknown): void {
  if (mode !== "write" && mode !== "check") {
    throw new Error("Unknown documentation plugin registry mode.");
  }
}

async function readRegistryOutput(root: string, tracked: readonly string[]): Promise<string> {
  try {
    if (!tracked.includes(registryPath)) {
      throw new Error("Untracked registry output.");
    }
    const previous = await readRepositoryFile(root, registryPath, true);
    if (previous.startsWith("\uFEFF") || new Files(root).read(registryPath) !== previous) {
      throw new Error("Noncanonical registry output.");
    }
    return previous;
  } catch {
    throw new Error(outputFailure);
  }
}

export async function generatePluginRegistry(
  root: string,
  mode: "write" | "check",
): Promise<readonly string[]> {
  validateRegistryMode(mode);
  const inventory = await trackedInventory(root);
  const previous = await readRegistryOutput(inventory.root, inventory.paths);
  const paths = await admitPluginPaths(inventory.root, inventory.paths);
  const source = renderPluginRegistry(paths);
  if ((await readRegistryOutput(inventory.root, inventory.paths)) !== previous) {
    throw new Error(outputFailure);
  }
  if (mode === "check") {
    if (previous !== source) {
      throw new Error("Documentation plugin registry is stale.");
    }
  } else if (previous !== source) {
    try {
      new Files(inventory.root).write(registryPath, source, previous);
    } catch {
      throw new Error(outputFailure);
    }
  }
  return paths;
}
